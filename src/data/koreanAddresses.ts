/**
 * Enhanced Korean address, postal code, building name, road name and bunji search engine.
 * Supports partial matching, building names, postal codes (우편번호), bunji numbers, and cities.
 */
export function searchAddressByBunji(query?: string): KoreanAddressItem[] {
  if (!query || !query.trim()) {
    return COMMON_KOREAN_ADDRESSES.slice(0, 15);
  }

  const rawQ = query.trim().toLowerCase();
  const numOnlyQ = rawQ.replace(/[^0-9]/g, '');

  return COMMON_KOREAN_ADDRESSES.filter((item) => {
    const rawBunji = item.bunjinumber.toLowerCase();
    const numOnlyBunji = rawBunji.replace(/[^0-9]/g, '');

    const matchBunji = rawBunji.includes(rawQ) || (numOnlyQ && numOnlyBunji.includes(numOnlyQ));
    const matchRoad = item.roadAddress.toLowerCase().includes(rawQ);
    const matchJibun = item.jibunAddress.toLowerCase().includes(rawQ);
    const matchZone = item.zonecode.includes(rawQ);
    const matchBuilding = item.buildingName?.toLowerCase().includes(rawQ) || false;
    const matchSido = item.sido.toLowerCase().includes(rawQ);
    const matchSigungu = item.sigungu.toLowerCase().includes(rawQ);

    return matchBunji || matchRoad || matchJibun || matchZone || matchBuilding || matchSido || matchSigungu;
  });
}
